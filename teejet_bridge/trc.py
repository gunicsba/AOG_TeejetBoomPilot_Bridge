"""PCAN-View trace files ($FILEVERSION=1.1): reader and rotating writer."""

from __future__ import annotations

import datetime as _dt
import os
import re
import threading
import time
from dataclasses import dataclass
from typing import Iterator, Optional

# "     1)        19.6  Rx     18EFFFC0  7  0A F4 14 A5 A2 26 00 "
_LINE = re.compile(
    r"^\s*(?P<num>\d+)\)\s+(?P<t>[\d.]+)\s+(?P<dir>Rx|Tx)\s+(?P<id>[0-9A-Fa-f]+)\s+(?P<dlc>\d+)\s*(?P<data>(?:[0-9A-Fa-f]{2}\s*)*)$"
)

_OLE_EPOCH = _dt.datetime(1899, 12, 30)


@dataclass
class TrcFrame:
    num: int
    t_ms: float
    direction: str      # "Rx" or "Tx"
    can_id: int
    data: bytes

    @property
    def dlc(self) -> int:
        return len(self.data)


def read_trc(path: str) -> Iterator[TrcFrame]:
    """Yield data frames from a PCAN-View v1.1 trace. Comments, error and
    status lines are skipped."""
    with open(path, "r", encoding="latin-1") as f:
        for line in f:
            if not line.strip() or line.lstrip().startswith(";"):
                continue
            m = _LINE.match(line.rstrip("\r\n"))
            if not m:
                continue
            dlc = int(m["dlc"])
            data = bytes.fromhex(m["data"].replace(" ", ""))[:dlc]
            yield TrcFrame(int(m["num"]), float(m["t"]), m["dir"], int(m["id"], 16), data)


def format_line(num: int, t_ms: float, direction: str, can_id: int, data: bytes) -> str:
    hexdata = " ".join(f"{b:02X}" for b in data)
    return f"{num:>6})  {t_ms:>10.1f}  {direction:<2}     {can_id:08X}  {len(data)}  {hexdata} "


class TrcWriter:
    """Thread-safe PCAN-View v1.1 writer with size-based rotation.

    Each rotated file gets its own header so every file opens in PCAN-View.
    Files: ``base.trc`` (current), ``base.1.trc`` ... ``base.N.trc`` (older).
    """

    def __init__(self, path: str, max_bytes: int = 5_000_000, backup_count: int = 5,
                 clock=time.monotonic):
        self.path = path
        self.max_bytes = max_bytes
        self.backup_count = backup_count
        self._clock = clock
        self._lock = threading.Lock()
        self._f = None
        self._num = 0
        self._t0 = 0.0
        d = os.path.dirname(os.path.abspath(path))
        os.makedirs(d, exist_ok=True)
        self._open_new()

    def _rotated_name(self, i: int) -> str:
        root, ext = os.path.splitext(self.path)
        return f"{root}.{i}{ext or '.trc'}"

    def _open_new(self):
        now = _dt.datetime.now()
        self._t0 = self._clock()
        self._num = 0
        self._f = open(self.path, "w", encoding="ascii", newline="\r\n")
        ole = (now - _OLE_EPOCH).total_seconds() / 86400.0
        self._f.write(
            ";$FILEVERSION=1.1\n"
            f";$STARTTIME={ole:.10f}\n"
            ";\n"
            f";   Start time: {now.strftime('%m/%d/%Y %H:%M:%S')}.{now.microsecond // 1000:03d}.0\n"
            ";   Generated by teejet-bridge\n"
            ";\n"
            ";   Message Number\n"
            ";   |         Time Offset (ms)\n"
            ";   |         |        Type\n"
            ";   |         |        |        ID (hex)\n"
            ";   |         |        |        |     Data Length\n"
            ";   |         |        |        |     |   Data Bytes (hex) ...\n"
            ";   |         |        |        |     |   |\n"
            ";---+--   ----+----  --+--  ----+---  +  -+ -- -- -- -- -- -- --\n"
        )

    def _rollover(self):
        self._f.close()
        if self.backup_count > 0:
            for i in range(self.backup_count - 1, 0, -1):
                src, dst = self._rotated_name(i), self._rotated_name(i + 1)
                if os.path.exists(src):
                    os.replace(src, dst)
            os.replace(self.path, self._rotated_name(1))
        self._open_new()

    def write(self, direction: str, can_id: int, data: bytes, t: Optional[float] = None):
        with self._lock:
            if self._f is None:
                return
            t = self._clock() if t is None else t
            self._num += 1
            self._f.write(format_line(self._num, (t - self._t0) * 1000.0, direction, can_id, data) + "\n")
            if self.max_bytes and self._f.tell() >= self.max_bytes:
                self._rollover()

    def flush(self):
        with self._lock:
            if self._f:
                self._f.flush()

    def close(self):
        with self._lock:
            if self._f:
                self._f.close()
                self._f = None
